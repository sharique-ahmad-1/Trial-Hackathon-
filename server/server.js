// server/server.js
import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';
import { createClient } from '@supabase/supabase-js';
import { z } from 'zod';

dotenv.config();

const app = express();
const PORT = process.env.PORT || 5000;

app.use(cors({
  origin: '*',
  methods: ['GET', 'POST', 'PUT', 'DELETE', 'OPTIONS'],
  allowedHeaders: ['Content-Type', 'Authorization']
}));

app.use(express.json({ limit: '10mb' }));

// Initialize Supabase Client
const supabaseUrl = process.env.SUPABASE_URL || 'https://kcodussczqgiagwtlrxw.supabase.co';
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseKey) {
  console.warn('[Warning] SUPABASE_SERVICE_ROLE_KEY is not defined in server/.env');
}

const supabase = createClient(supabaseUrl, supabaseKey || '');

// Gemini API Key
const GEMINI_API_KEY = process.env.GEMINI_API_KEY;

// Validation Schema for Advisory Request
const advisorySchema = z.object({
  crop_name: z.string().min(1, 'Crop name is required'),
  symptoms: z.string().min(3, 'Symptoms description is required'),
  growth_stage: z.string().optional().default('Vegetative'),
  weather_condition: z.string().optional().default('Normal / Sunny'),
  soil_condition: z.string().optional().default('Loamy Soil'),
  crop_id: z.string().optional().nullable(),
  user_id: z.string().optional().default('farmer_demo_1')
});

// Helper: Call Gemini REST API with Structured Prompt
async function callGeminiAdvisor(payload) {
  const prompt = `
You are an expert Agronomist, Plant Pathologist, and Principal Agricultural Advisor for CropPilot AI.
Analyze the following crop diagnosis request and return a comprehensive, actionable, and scientifically accurate agricultural advisory.

Crop Information:
- Crop Name: ${payload.crop_name}
- Symptoms Observed: ${payload.symptoms}
- Growth Stage: ${payload.growth_stage}
- Weather / Climate: ${payload.weather_condition}
- Soil Condition: ${payload.soil_condition}

Respond strictly in valid JSON format matching this structure:
{
  "condition_identified": "Specific disease, pest infestation, or physiological disorder name",
  "pathogen_or_cause": "e.g., Fungal pathogen (Alternaria solani) or Nutrient deficiency",
  "severity": "Low" | "Moderate" | "High" | "Critical",
  "confidence_score": 95,
  "summary": "Brief 1-2 sentence overview of the diagnosis.",
  "immediate_actions": [
    "Step 1 to stop spread immediately",
    "Step 2"
  ],
  "organic_remedies": [
    { "remedy": "Neem oil spray (3-5 ml/L)", "application": "Spray early morning or late evening every 7 days" }
  ],
  "chemical_remedies": [
    { "remedy": "Copper Oxychloride or Mancozeb 75% WP", "application": "2g per liter water on affected foliage", "precautions": "Wear mask and adhere to safety pre-harvest intervals" }
  ],
  "preventive_measures": [
    "Ensure proper plant spacing for air circulation",
    "Practice crop rotation with non-host crops"
  ],
  "irrigation_advice": "Recommended watering schedule to prevent moisture-induced fungal spread",
  "fertilizer_advice": "Nutrient balancing advice (e.g. reduce excess nitrogen)",
  "disclaimer": "This advisory is generated by CropPilot AI based on symptom analysis. For severe or large-scale crop failures, consult your local district agricultural extension officer."
}
Only output the JSON object. Do not include markdown code block backticks.
`;

  const modelsToTry = ['gemini-3.7-flash', 'gemini-flash-latest', 'gemini-3.8-flash'];
  let lastError = null;

  for (const model of modelsToTry) {
    try {
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${GEMINI_API_KEY}`;
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: {
            temperature: 0.2,
            responseMimeType: "application/json"
          }
        })
      });

      if (!response.ok) {
        const errorText = await response.text();
        console.warn(`[Gemini] ${model} returned ${response.status}: ${errorText.slice(0, 100)}`);
        lastError = new Error(`Gemini error: ${errorText}`);
        continue;
      }

      const data = await response.json();
      const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
      if (rawText) {
        const cleaned = rawText.replace(/```json/g, '').replace(/```/g, '').trim();
        return JSON.parse(cleaned);
      }
    } catch (e) {
      lastError = e;
    }
  }

  throw lastError || new Error('Failed to generate advisory from all models');
}

// ----------------- API ROUTES -----------------

// 1. Health Check
app.get('/api/health', async (req, res) => {
  let supabaseConnected = false;
  try {
    const { error } = await supabase.from('farms').select('count', { count: 'exact', head: true });
    supabaseConnected = !error;
  } catch (e) {
    supabaseConnected = false;
  }

  res.json({
    status: 'healthy',
    timestamp: new Date().toISOString(),
    services: {
      server: 'running',
      supabase: supabaseConnected ? 'connected' : 'error',
      gemini: !!GEMINI_API_KEY ? 'configured' : 'missing_key'
    }
  });
});

// 2. Farms Management
app.get('/api/farms', async (req, res) => {
  try {
    const { data, error } = await supabase
      .from('farms')
      .select('*, fields(*, crops(*))')
      .order('created_at', { ascending: false });

    if (error) throw error;
    res.json(data);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

app.post('/api/farms', async (req, res) => {
  try {
    const { name, location, total_area_acres, user_id } = req.body;
    if (!name || !location) {
      return res.status(400).json({ error: 'Name and location are required' });
    }

    const { data, error } = await supabase
      .from('farms')
      .insert([{ 
        name, 
        location, 
        total_area_acres: parseFloat(total_area_acres) || 0,
        user_id: user_id || 'farmer_demo_1' 
      }])
      .select()
      .single();

    if (error) throw error;
    res.status(201).json(data);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

