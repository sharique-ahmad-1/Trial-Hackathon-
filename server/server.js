// 5. AI Crop Advisory Diagnosis
app.post('/api/advisories/diagnose', async (req, res) => {
  try {
    const parseResult = advisorySchema.safeParse(req.body);
    if (!parseResult.success) {
      return res.status(400).json({ error: parseResult.error.errors[0].message });
    }

    const payload = parseResult.data;
    console.log(`[Diagnosis] Dispatching AI diagnosis for ${payload.crop_name}...`);

    // Call Gemini AI
    const aiResult = await callGeminiAdvisor(payload);

    // Save into Supabase Database
    const { data: savedAdvisory, error: dbError } = await supabase
      .from('advisories')
      .insert([{
        user_id: payload.user_id,
        crop_id: payload.crop_id || null,
        crop_name: payload.crop_name,
        symptoms: payload.symptoms,
        growth_stage: payload.growth_stage,
        weather_condition: payload.weather_condition,
        soil_condition: payload.soil_condition,
        diagnosis: aiResult.condition_identified,
        severity: ['Low', 'Moderate', 'High', 'Critical'].includes(aiResult.severity) ? aiResult.severity : 'Moderate',
        organic_remedies: aiResult.organic_remedies || [],
        chemical_remedies: aiResult.chemical_remedies || [],
        preventive_measures: aiResult.preventive_measures || [],
        irrigation_advice: aiResult.irrigation_advice || '',
        disclaimer: aiResult.disclaimer || '',
        raw_ai_response: aiResult
      }])
      .select()
      .single();

    if (dbError) {
      console.warn('[Database] Failed to persist advisory:', dbError.message);
    }

    res.json({
      success: true,
      advisory_id: savedAdvisory?.id || null,
      created_at: savedAdvisory?.created_at || new Date().toISOString(),
      diagnosis_data: aiResult
    });
  } catch (err) {
    console.error('[Diagnosis] Error processing request:', err);
    res.status(500).json({ error: err.message || 'Failed to generate advisory' });
  }
});

